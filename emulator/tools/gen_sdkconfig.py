#!/usr/bin/env python3
"""Generate the emulator's sdkconfig.h from the badge's own configuration.

The badge build resolves Kconfig into firmware/sdkconfig. The emulator reuses
that file so LVGL (built in Kconfig mode, LV_CONF_SKIP + an external Kconfig
header) and the firmware sources see exactly the CONFIG_* values the badge
does. sdkconfig.defaults is applied on top, so an option just added there
(e.g. CONFIG_LV_USE_QRCODE=y) takes effect before the badge is rebuilt.

    gen_sdkconfig.py <firmware dir> <out sdkconfig.h>
"""
import os
import re
import sys

# Values that must differ in the browser. Keep this list short: every entry
# is a place where the emulator does not match the badge.
OVERRIDES = {
    "CONFIG_LV_OS_NONE": "y",       # cooperative tasks; LVGL runs on the scheduler loop
    "CONFIG_LV_USE_OS": "0",
    "CONFIG_LV_DRAW_SW_ASM_NONE": "y",
    "CONFIG_LV_USE_DRAW_SW_ASM": "0",
    "CONFIG_LV_BUILD_EXAMPLES": None,
    "CONFIG_LV_BUILD_DEMOS": None,
}

LINE = re.compile(r"^(CONFIG_[A-Za-z0-9_]+)=(.*)$")
UNSET = re.compile(r"^# (CONFIG_[A-Za-z0-9_]+) is not set$")


def parse(path, into):
    with open(path) as f:
        for raw in f:
            line = raw.strip()
            m = LINE.match(line)
            if m:
                into[m.group(1)] = None if m.group(2) == "n" else m.group(2)
                continue
            m = UNSET.match(line)
            if m:
                into[m.group(1)] = None


def main():
    fw, out = sys.argv[1], sys.argv[2]
    sdkconfig = os.path.join(fw, "sdkconfig")
    defaults = os.path.join(fw, "sdkconfig.defaults")
    if not os.path.exists(sdkconfig):
        sys.exit("gen_sdkconfig: firmware/sdkconfig is missing. Configure the badge once "
                 "(idf.py reconfigure or idf.py build) so the emulator can reuse its config.")
    cfg = {}
    parse(sdkconfig, cfg)
    overlay = {}
    parse(defaults, overlay)
    for k, v in overlay.items():
        if cfg.get(k, None) != v:
            if k in cfg:
                print(f"gen_sdkconfig: {k} differs from sdkconfig, using sdkconfig.defaults", file=sys.stderr)
            cfg[k] = v
    cfg.update(OVERRIDES)

    lines = ["/* Generated by firmware/emulator/tools/gen_sdkconfig.py from firmware/sdkconfig",
             " * (+ sdkconfig.defaults). Do not edit. */", "#pragma once", ""]
    for k in sorted(cfg):
        v = cfg[k]
        if v is None:
            continue
        if v == "y":
            v = "1"
        lines.append(f"#define {k} {v}")
    text = "\n".join(lines) + "\n"
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    if not os.path.exists(out) or open(out).read() != text:
        with open(out, "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
