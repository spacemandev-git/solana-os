#!/usr/bin/env python3
# Convert a PNG to an LVGL 9 RGB565A8 image descriptor (C source).
# usage: python3 tools/img2lvgl.py <in.png> <symbol_name> <out.c> [height]
import sys
from PIL import Image

src, name, out = sys.argv[1:4]
img = Image.open(src).convert("RGBA")
if len(sys.argv) > 4:
    h = int(sys.argv[4])
    img = img.resize((round(img.width * h / img.height), h), Image.LANCZOS)
w, h = img.size
px = list(img.getdata())
color, alpha = bytearray(), bytearray()
for r, g, b, a in px:
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    color += bytes((v & 0xFF, v >> 8))
    alpha.append(a)
data = color + alpha

with open(out, "w") as f:
    f.write(f"// Generated by tools/img2lvgl.py from {src.split('/')[-1]}. Do not edit.\n")
    f.write('#include "lvgl.h"\n\n')
    f.write(f"static const uint8_t {name}_map[] = {{\n")
    for i in range(0, len(data), 24):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
    f.write("};\n\n")
    f.write(f"const lv_image_dsc_t {name} = {{\n"
            f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8,\n"
            f"                .w = {w}, .h = {h}, .stride = {w * 2} }},\n"
            f"    .data_size = sizeof({name}_map),\n"
            f"    .data = {name}_map,\n}};\n")
print(f"{out}: {w}x{h}")
